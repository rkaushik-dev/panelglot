"""A single HTML file somebody can open without installing anything.

This exists because the people who need to see it are not developers. The
production manager wants to know whether Turkish is ready, and the answer is
not a JUnit XML in a CI artefact.

One file, no external anything. It gets attached to an email and forwarded to
a distributor, and half the time it is opened from a Downloads folder on a
machine with no network. A stylesheet on a CDN would make it look broken to
exactly the people it is for.

No JavaScript either, for the same reason and because several of the machines
this lands on are the panel PCs, running a browser old enough that anything
clever fails silently.
"""

