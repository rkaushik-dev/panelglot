def render_report(result: CheckResult, stats: ProjectStats | None = None, *,
                  limit: int = 25, today: date | None = None) -> str:
    """One HTML page for a check run."""
    stamp = (today or date.today()).isoformat()
    project = escape(result.catalog.project)

    parts = [
        "<!doctype html>",
        # Tags are closed the XHTML way. Browsers do not care and the test
        # that parses this as XML does, which is the cheapest way to catch a
        # tag left open by a string built in four places.
        '<html lang="en"><head><meta charset="utf-8"/>',
        '<meta name="viewport" content="width=device-width, initial-scale=1"/>',
        f"<title>{project} localisation</title>",
        f"<style>{STYLE}</style>",
        "</head><body>",
        f"<h1>{project}</h1>",
        f'<p class="subtitle">Localisation report, {escape(stamp)}</p>',
    ]

    parts.append(_coverage_table(result, stats))
    parts.append(_findings(result, limit))

    parts.extend([
        f'<footer>Generated by v4t-translate. {escape(result.report.summary())}'
        f"</footer>",
        "</body></html>",
    ])
    return "\n".join(parts) + "\n"


def _coverage_table(result: CheckResult, stats: ProjectStats | None) -> str:
    rows = ["<h2>Languages</h2>", "<table>",
            "<tr><th>Language</th><th>Panel</th><th>Approved</th>"
            "<th></th><th class='num'>Words left</th></tr>"]

    for check in result.locales:
        locale_stats = stats.locale(check.tag) if stats else None
        approved = locale_stats.approved if locale_stats else check.translated
        total = locale_stats.total if locale_stats else check.total
        fraction = (approved / total) if total else 0.0
        words = locale_stats.outstanding_words if locale_stats else 0

        rows.append(
            f"<tr><td>{escape(check.tag)}</td>"
            f"<td>{escape(check.panel.name)}</td>"
            f"<td class='num'>{approved} / {total}</td>"
            f"<td><div class='bar'><span style='width:{fraction:.1%}'></span></div></td>"
            f"<td class='num'>{words}</td></tr>"
        )

    rows.append("</table>")

    if any(check.font_is_fallback for check in result.locales):
        fallbacks = ", ".join(
            escape(c.tag) for c in result.locales if c.font_is_fallback
        )
        rows.append(
            f"<p class='detail'>No font metrics for {fallbacks}. "
            f"Fitting numbers for those languages are approximate.</p>"
        )

    return "\n".join(rows)


def _findings(result: CheckResult, limit: int) -> str:
    if not result.report:
        return (
            "<h2>Findings</h2>"
            f"<p class='clean'>Nothing found across "
            f"{result.report.checked} translated messages.</p>"
        )

    parts = ["<h2>Findings</h2>"]

    for rule, findings in result.report.by_rule().items():
        worst = max(f.severity for f in findings)
        parts.append(
            f"<h3>{escape(rule)} "
            f"<span class='summary'>({len(findings)}, worst {worst})</span></h3>"
        )

        shown = findings if limit <= 0 else findings[:limit]
        parts.extend(_finding(finding) for finding in shown)

        hidden = len(findings) - len(shown)
        if hidden:
            parts.append(f"<p class='detail'>and {hidden} more</p>")

    return "\n".join(parts)


def _finding(finding: Finding) -> str:
    css = {Severity.ERROR: "error", Severity.WARNING: "warning",
           Severity.INFO: "info"}[finding.severity]

    lines = [f"<div class='finding {css}'>"]
    lines.append(
        f"<div><span class='text'>{escape(finding.source_text)}</span>"
        f" &rarr; <span class='text'>{escape(finding.translated_text)}</span></div>"
    )
    lines.append(f"<div class='summary'>{escape(finding.locale)}: "
                 f"{escape(finding.summary)}</div>")
    if finding.detail:
        lines.append(f"<div class='detail'>{escape(finding.detail)}</div>")
    if finding.origin:
        lines.append(f"<div class='origin'>{escape(finding.origin)}</div>")
    lines.append("</div>")
    return "".join(lines)
