"""Reading a BDF font into metrics.

The panel fonts are built from BDF by a tool in the firmware tree, and the
``.fmx`` files this package measures with were being written by hand from what
that tool printed. Two of them were wrong, in the direction that makes a
translation look like it fits when it does not, which is the worst direction.

So the metrics come out of the BDF now. Only two things are read from it: the
advance width of each glyph and which codepoints exist. The bitmaps are
ignored, which is why this is fifty lines rather than a font library.

The advance is ``DWIDTH``, not the bounding box. They differ for any glyph
with side bearing, which on a proportional font is most of them, and using
the bounding box undercounts every string. That was one of the two wrong
files.
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path

from ..errors import SourceError
from .font import FontMetrics

__all__ = ["read_bdf", "load_bdf", "metrics_to_fmx"]


def read_bdf(text: str, *, path: str | None = None) -> FontMetrics:
    """Parse BDF text into :class:`~.font.FontMetrics`."""
    where = path or "<bdf>"

    name = ""
    pixel_size = 0
    line_height = 0
    default_width = 0
    widths: dict[int, int] = {}

    current_encoding: int | None = None
    in_bitmap = False
    seen_start = False

    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line:
            continue

        if in_bitmap:
            if line == "ENDCHAR":
                in_bitmap = False
            continue

        keyword, _, rest = line.partition(" ")
        rest = rest.strip()

        if keyword == "STARTFONT":
            seen_start = True
        elif keyword == "FONT":
            name = _family_from(rest) or rest
        elif keyword == "PIXEL_SIZE":
            pixel_size = _int(rest, where, number)
        elif keyword == "SIZE":
            pixel_size = pixel_size or _int(rest.split()[0], where, number)
        elif keyword == "FONTBOUNDINGBOX":
            parts = rest.split()
            if len(parts) >= 2:
                line_height = line_height or _int(parts[1], where, number)
        elif keyword == "STARTCHAR":
            current_encoding = None
        elif keyword == "ENCODING":
            value = _int(rest.split()[0], where, number)
            current_encoding = value if value >= 0 else None
        elif keyword == "DWIDTH":
            width = _int(rest.split()[0], where, number)
            if current_encoding is not None:
                widths[current_encoding] = width
        elif keyword == "BITMAP":
            in_bitmap = True

    if not seen_start:
        raise SourceError(f"{where}: no STARTFONT, this is not a BDF font")
    if not widths:
        raise SourceError(f"{where}: no glyphs with an encoding and a DWIDTH")

    if not default_width:
        default_width = _most_common(widths.values())

    metrics = FontMetrics(
        name=name or Path(where).stem,
        pixel_size=pixel_size or line_height or 8,
        line_height=line_height,
        default_width=default_width,
        widths=widths,
    )
    metrics.__post_init__()
    return metrics


def load_bdf(path: Path | str) -> FontMetrics:
    """Read a BDF font from disk."""
    path = Path(path)
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except FileNotFoundError as exc:
        raise SourceError(f"{path} does not exist") from exc
    return read_bdf(text, path=str(path))


def metrics_to_fmx(metrics: FontMetrics, *, source: str = "") -> str:
    """Render metrics in the format :func:`~.font.parse_metrics` reads.

    Ranges are collapsed where consecutive codepoints share a width, because a
    CJK font has twenty thousand glyphs and one line each is a file nobody can
    look at.
    """
    lines = [
        f"# Generated by v4t-translate from {source or 'a BDF font'}.",
        "# Do not edit by hand. Rebuild it from the BDF instead.",
        f"name: {metrics.name}",
        f"pixel_size: {metrics.pixel_size}",
        f"line_height: {metrics.line_height}",
        f"default_width: {metrics.default_width}",
        "",
    ]

    for low, high, width in _collapse(metrics.widths):
        if low == high:
            lines.append(f"{low:04X} {width}")
        else:
            lines.append(f"{low:04X}..{high:04X} {width}")

    return "\n".join(lines) + "\n"


def _collapse(widths: dict[int, int]) -> Iterator[tuple[int, int, int]]:
    """Consecutive codepoints with the same width, as ranges."""
    ordered = sorted(widths.items())
    if not ordered:
        return

    start, width = ordered[0]
    previous = start

    for codepoint, this_width in ordered[1:]:
        if codepoint == previous + 1 and this_width == width:
            previous = codepoint
            continue
        yield (start, previous, width)
        start = previous = codepoint
        width = this_width

    yield (start, previous, width)


def _family_from(xlfd: str) -> str:
    """The family name out of an XLFD, which is the second dash separated field."""
    parts = xlfd.split("-")
    if len(parts) < 3 or not parts[2]:
        return ""
    return parts[2]


def _most_common(values) -> int:
    """The advance to charge a covered glyph that has no explicit width.

    Ties break toward the wider one. Undercounting is the direction that makes
    a translation look like it fits when it does not, and that is the failure
    this whole module exists to stop.
    """
    counts: dict[int, int] = {}
    for value in values:
        counts[value] = counts.get(value, 0) + 1
    if not counts:
        return 1
    return max(counts.items(), key=lambda item: (item[1], item[0]))[0]


def _int(text: str, where: str, line: int) -> int:
    try:
        return int(text)
    except ValueError as exc:
        raise SourceError(f"{where}:{line}: expected a number, got {text!r}") from exc
