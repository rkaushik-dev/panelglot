"""Writing ``res/values-<qualifier>/strings.xml`` for V4T-Mobile.

Android picks a translation by directory name, not by anything inside the
file, and the qualifier grammar is its own thing: ``values-de`` for German,
``values-zh-rTW`` for Traditional Chinese, with the region prefixed by ``r``
and no hyphen before it. Getting the directory wrong produces a build that
compiles, installs and shows English, which is the hardest kind of bug to
notice because everything looks like it worked.

Only translated strings are written. Android falls back to the default
``values/`` directory for anything missing, which is exactly the behaviour we
want and is better than writing English into a German file, where it would
look deliberate.
"""

from __future__ import annotations

from xml.sax.saxutils import escape

from ..catalog.model import OriginKind
from ..catalog.store import Catalog
from ..catalog.translations import TranslationSet
from ..locales import Locale
from ..sources.androidxml import escape_android
from .base import EmitOptions, EmitResult

__all__ = ["AndroidXmlEmitter", "qualifier_for", "values_directory"]

_HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
_NOTE = (
    "<!-- Generated by v4t-translate. Edit the catalog, not this file. -->\n"
)

#: Languages Android knows by an obsolete code. The platform still expects the
#: old one in a resource qualifier and rejects the current one.
_LEGACY_CODES = {"he": "iw", "id": "in", "yi": "ji"}


def qualifier_for(locale: Locale) -> str:
    """The resource qualifier for a locale: ``de``, ``zh-rTW``, ``pt-rBR``."""
    parts = locale.tag.split("-")
    language = _LEGACY_CODES.get(parts[0].lower(), parts[0].lower())

    if len(parts) == 1:
        return language

    region = parts[-1]
    if len(region) == 2 and region.isalpha():
        return f"{language}-r{region.upper()}"
    return language


def values_directory(locale: Locale) -> str:
    return f"values-{qualifier_for(locale)}"


class AndroidXmlEmitter:
    """Writes one ``strings.xml``."""

    kind = "androidxml"

    def emit(self, catalog: Catalog, translations: TranslationSet,
             options: EmitOptions) -> EmitResult:
        result = EmitResult(path=options.path)

        lines = [_HEADER, _NOTE, "<resources>\n"]

        for key in catalog.sorted_keys():
            message = catalog.messages[key]
            names = _android_names(message)
            if not names:
                continue

            translation = translations.get(key)

            if not translation.text:
                result.skipped.append(key)
                continue

            if message.protected:
                # translatable="false" in the source. Writing it into a
                # localised file is an aapt error, not a warning.
                result.skipped.append(key)
                continue

            for name in names:
                lines.append(_element(name, translation.text))
            result.written += 1

        lines.append("</resources>\n")

        options.path.parent.mkdir(parents=True, exist_ok=True)
        data = "".join(lines).encode("utf-8")
        options.path.write_bytes(data)
        result.bytes_written = len(data)
        return result


def _android_names(message) -> list[str]:
    """Resource names this message answers to, deduplicated and ordered."""
    names: list[str] = []
    for origin in message.origins:
        if origin.kind is not OriginKind.ANDROID_STRING:
            continue
        if origin.symbol not in names:
            names.append(origin.symbol)
    return names


def _element(name: str, text: str) -> str:
    """One resource element.

    Two layers of escaping and they are not the same. XML escaping handles the
    angle brackets and ampersands so the file parses. Android escaping handles
    the apostrophe and the surrounding quotes so the platform's own string
    reader gives back what was meant. Both are needed and in this order.
    """
    if "[" in name:
        base, _, rest = name.partition("[")
        index = rest.rstrip("]")
        return f'  <!-- {base} item {index} -->\n  <string name="{_id(name)}">' \
               f'{_body(text)}</string>\n'
    return f'  <string name="{name}">{_body(text)}</string>\n'


def _id(name: str) -> str:
    """Flatten a plural or array symbol into something aapt accepts."""
    return name.replace("[", "_").replace("]", "")


def _body(text: str) -> str:
    return escape(escape_android(text))
