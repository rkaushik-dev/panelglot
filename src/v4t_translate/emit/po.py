"""Gettext PO output.

Nobody in this product's chain uses gettext. One of the German agencies uses a
CAT tool that imports PO and nothing else, and producing a file it can read
was cheaper than arguing about it, so this exists for exactly that.

It is a one way export. Their answers come back as a workbook like everybody
else's, because writing a PO reader that tolerates what a CAT tool does to
comments and flags is a project of its own.

The parts that matter:

Every message carries its key as a ``msgctxt``. Without it, two different
messages with the same English collide in the PO, and a CAT tool merges them
silently.

Source references go in ``#:`` comments, developer notes in ``#.``, and the
character or pixel budget goes in a ``#.`` note too because there is nowhere
better and translators do read those.

Untranslated entries are written with an empty ``msgstr`` rather than left
out. A PO with holes in it looks finished to a tool that counts entries.
"""

from __future__ import annotations

from datetime import date

from ..catalog.store import Catalog
from ..catalog.translations import TranslationSet, TranslationState
from .base import EmitOptions, EmitResult

__all__ = ["PoEmitter", "po_quote"]

#: States that mean the entry is not to be trusted as it stands.
_FUZZY_STATES = frozenset({TranslationState.DRAFT, TranslationState.NEEDS_REVIEW})


def po_quote(text: str) -> list[str]:
    """Render a string as one or more PO quoted lines.

    Multi-line values are written with an empty first line and one line per
    source line, which is the convention every PO tool expects and several
    of them enforce.
    """
    escaped = (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\t", "\\t")
    )

    if "\n" not in escaped:
        return [f'"{escaped}"']

    pieces = escaped.split("\n")
    lines = ['""']
    for index, piece in enumerate(pieces):
        suffix = "\\n" if index < len(pieces) - 1 else ""
        lines.append(f'"{piece}{suffix}"')
    return lines


class PoEmitter:
    """Writes a gettext catalog."""

    kind = "po"

    def emit(self, catalog: Catalog, translations: TranslationSet,
             options: EmitOptions) -> EmitResult:
        result = EmitResult(path=options.path)
        lines = self._header(catalog, options)

        for key in catalog.sorted_keys():
            message = catalog.messages[key]
            translation = translations.get(key)

            lines.append("")
            lines.extend(self._comments(message, translation))
            lines.extend(self._field("msgctxt", key))
            lines.extend(self._field("msgid", message.source_text))
            lines.extend(self._field("msgstr", translation.text))

            if translation.text:
                result.written += 1
            else:
                result.skipped.append(key)

        options.path.parent.mkdir(parents=True, exist_ok=True)
        data = ("\n".join(lines) + "\n").encode("utf-8")
        options.path.write_bytes(data)
        result.bytes_written = len(data)
        return result

    @staticmethod
    def _header(catalog: Catalog, options: EmitOptions) -> list[str]:
        stamp = date.today().isoformat()
        return [
            f"# {catalog.project} translations for {options.locale.english_name}.",
            "# Generated by v4t-translate. Do not edit; edit the catalog.",
            "#",
            'msgid ""',
            'msgstr ""',
            f'"Project-Id-Version: {catalog.project}\\n"',
            f'"PO-Revision-Date: {stamp}\\n"',
            f'"Language: {options.locale.tag}\\n"',
            '"MIME-Version: 1.0\\n"',
            '"Content-Type: text/plain; charset=UTF-8\\n"',
            '"Content-Transfer-Encoding: 8bit\\n"',
            f'"X-Source-Language: {catalog.source_locale}\\n"',
        ]

    @staticmethod
    def _comments(message, translation) -> list[str]:
        lines: list[str] = []

        if message.developer_note:
            lines.append(f"#. {message.developer_note}")

        budget = _budget(message)
        if budget:
            lines.append(f"#. Space: {budget}")

        if message.protected:
            lines.append("#. Do not translate. This string ships unchanged.")

        for origin in message.origins:
            lines.append(f"#: {origin.describe()}")

        flags = []
        if translation.state in _FUZZY_STATES:
            flags.append("fuzzy")
        if "%" in message.source_text:
            flags.append("c-format")
        if flags:
            lines.append(f"#, {', '.join(flags)}")

        return lines

    @staticmethod
    def _field(name: str, value: str) -> list[str]:
        quoted = po_quote(value)
        return [f"{name} {quoted[0]}", *quoted[1:]]


def _budget(message) -> str:
    if message.max_chars:
        return f"{message.max_chars} characters"
    if message.max_width_px:
        lines = f" over {message.max_lines} lines" if message.max_lines > 1 else ""
        return f"{message.max_width_px} pixels{lines}"
    return ""
