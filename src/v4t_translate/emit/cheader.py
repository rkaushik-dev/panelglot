"""Writing a localised C string table.

Used for the products that still link their languages in rather than loading a
pack: two of the older Mini boards do, and the build for those needs a
``lng_de.h`` sitting beside ``lng_en.h``.

The output is designated initialisers whatever the input used, because the
positional form is only safe if the enum has not changed and this file is
generated separately from the firmware that consumes it. Designated form is
wrong loudly, at compile time, if an id disappears. Positional form is wrong
quietly, at runtime, on the operator's line.
"""

from __future__ import annotations

from ..catalog.model import Origin, OriginKind
from ..catalog.store import Catalog
from ..catalog.translations import TranslationSet
from ..errors import EmitError
from .base import EmitOptions, EmitResult

__all__ = ["CHeaderEmitter", "escape_c_string"]

_C_ESCAPES = {
    "\\": "\\\\",
    '"': '\\"',
    "\n": "\\n",
    "\r": "\\r",
    "\t": "\\t",
}


def escape_c_string(text: str, *, codepage: int | None = None) -> str:
    """Escape a string for a C literal.

    Anything outside printable ASCII is written as a hex escape when the file
    is destined for an 8-bit build. A compiler reading a UTF-8 source with a
    cp1252 execution character set does something implementation defined with
    a literal umlaut, and hex escapes take the question out of it.
    """
    out: list[str] = []
    for char in text:
        replacement = _C_ESCAPES.get(char)
        if replacement is not None:
            out.append(replacement)
            continue
        if 0x20 <= ord(char) < 0x7F:
            out.append(char)
            continue
        out.append(_hex(char, codepage))
    return "".join(out)


def _hex(char: str, codepage: int | None) -> str:
    if codepage is None:
        # C99 universal character name. The compiler puts it into whatever
        # the execution charset is, which for these builds is UTF-8.
        return f"\\u{ord(char):04X}"
    try:
        encoded = char.encode(f"cp{codepage}")
    except (UnicodeEncodeError, LookupError) as exc:
        raise EmitError(
            f"{char!r} cannot be written in codepage {codepage}"
        ) from exc
    # A hex escape swallows following hex digits, so each byte is closed by
    # restarting the literal. "\x41" "2" is A2; "\x412" is not.
    return "".join(f'\\x{byte:02X}""' for byte in encoded)


class CHeaderEmitter:
    """Writes a localised ``lng_<tag>.h``."""

    kind = "cheader"

    container = "lng_en"

    def __init__(self, container: str | None = None) -> None:
        if container:
            self.container = container

    def emit(self, catalog: Catalog, translations: TranslationSet,
             options: EmitOptions) -> EmitResult:
        result = EmitResult(path=options.path)
        slots = self._slots(catalog)
        if not slots:
            raise EmitError(
                f"no messages came from a {self.container!r} table"
            )

        tag = options.locale.tag
        array = f"lng_{tag.split('-')[0].lower()}"
        guard = f"V4T_LANG_{tag.replace('-', '_').upper()}_H"
        codepage = None if options.encoding == "utf-8" else options.locale.codepage

        width = max(len(origin.symbol) for _, origin in slots) + 4

        lines = [
            f"/* Generated by v4t-translate for {options.locale.english_name}.",
            " * Do not edit. Edit the catalog and rebuild.",
            " */",
            f"#ifndef {guard}",
            f"#define {guard}",
            "",
            f'static const char * const {array}[LNG_COUNT] = {{',
        ]

        for key, origin in slots:
            message = catalog.messages[key]
            translation = translations.get(key)

            if translation.text:
                text = translation.text
                result.written += 1
                trailer = ""
            elif options.fallback_to_source:
                text = message.source_text
                result.fell_back.append(key)
                trailer = "  /* untranslated */"
            else:
                text = ""
                result.skipped.append(key)
                trailer = "  /* untranslated */"

            slot = f"[{origin.symbol}]".ljust(width)
            lines.append(f'    {slot}= "{escape_c_string(text, codepage=codepage)}",'
                         f"{trailer}")

        lines.extend(["};", "", f"#endif /* {guard} */", ""])

        options.path.parent.mkdir(parents=True, exist_ok=True)
        data = "\n".join(lines).encode("ascii")
        options.path.write_bytes(data)
        result.bytes_written = len(data)
        return result

    def _slots(self, catalog: Catalog) -> list[tuple[str, Origin]]:
        found: list[tuple[int, str, str, Origin]] = []
        for key, message in catalog.messages.items():
            for origin in message.origins:
                if origin.kind is OriginKind.C_STRING_TABLE and \
                        origin.container == self.container:
                    found.append((origin.line, origin.source, key, origin))
        found.sort()

        seen: set[str] = set()
        slots: list[tuple[str, Origin]] = []
        for _, _, key, origin in found:
            if origin.symbol in seen:
                continue
            seen.add(origin.symbol)
            slots.append((key, origin))
        return slots
